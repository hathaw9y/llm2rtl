        #1; check(1'b1, 1'b1);
        #4; {clock, a} = 2'b10;
        #1; check(1'b0, 1'b1);
        #4; {clock, a} = 2'b01;
        #1; check(1'b0, 1'b0);
        $display("PASS: %0d waveform and directed checks", checks);
        $finish;
    end
endmodule
