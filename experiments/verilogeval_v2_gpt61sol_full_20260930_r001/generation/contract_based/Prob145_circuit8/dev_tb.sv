`timescale 1ns/1ps
module dev_tb;
    logic clock, a;
    wire p, q;
    integer checks = 0;
    TopModule dut (.clock(clock), .a(a), .p(p), .q(q));
    task automatic check(input logic ep, input logic eq);
        begin
            if (p !== ep || q !== eq)
                $fatal(1, "Mismatch at %0t: p=%b q=%b expected p=%b q=%b", $time, p, q, ep, eq);
            checks = checks + 1;
        end
    endtask
    initial begin
        #1000;
        $fatal(1, "Watchdog timeout");
    end
    initial begin
        {clock, a} = 2'b00;
        #1; check(1'bx, 1'bx);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'bx, 1'bx);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'bx, 1'bx);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'bx, 1'bx);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'bx, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'bx);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b01;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b01;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b11;
        #1; check(1'b1, 1'b0);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b11;
        #1; check(1'b1, 1'b0);
        #4;
        {clock, a} = 2'b10;
        #1; check(1'b0, 1'b0);
        #4;
        {clock, a} = 2'b11;
        #1; check(1'b1, 1'b0);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b1, 1'b1);
        #4;
        {clock, a} = 2'b01;
        #1; check(1'b1, 1'b1);
        #4;
        {clock, a} = 2'b00;
        #1; check(1'b1, 1'b1);
        #4;
        {clock, a} = 2'b01;
